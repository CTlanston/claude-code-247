import { join } from 'path'
import { mkdirSync } from 'fs'
import type { Task, RunnerConfig, RunResult } from '@aedev/core'
import { generateId } from '@aedev/core'
import { EvidenceWriter } from './evidence.js'
import type { RunnerInterface } from './runner-interface.js'

export class MockRunner implements RunnerInterface {
  async run(task: Task, config: RunnerConfig): Promise<RunResult> {
    const start = Date.now()
    const runId = generateId()
    const evidenceDir = join(config.outputBaseDir, task.id)
    mkdirSync(evidenceDir, { recursive: true })
    const w = new EvidenceWriter(evidenceDir)

    // Simulate a short delay
    await new Promise((r) => setTimeout(r, 100))

    w.writePlan(`# Plan\n\nTask: ${task.title}\nPrompt: ${task.prompt}\n\nThis is a mock plan generated by MockRunner.`)
    w.writeDiffSummary(`# Diff Summary\n\nMock diff: no files changed (mock run).`)
    w.writeTestSummary(`# Test Summary\n\nMock tests: all passed (mock run).`)
    w.writeDoneReport(`# Done Report\n\nTask ${task.id} completed by MockRunner.\nExit code: 0`)

    return { runId, taskId: task.id, exitCode: 0, evidenceDir, durationMs: Date.now() - start }
  }
}
