"""action_evaluator — Track S4 (L7 §6).

Score-based safety gate for shell / git commands. Given a command
string, returns an `ActionScore` with:
- `safe: bool`  (score < threshold)
- `score: int 0..100`
- `flags: List[ActionFlag]`  (each pattern matched)

This is NOT an executor — it does not run anything. Callers consult
the score before invoking subprocess. The point is to catch obviously
unsafe commands (rm -rf /, sudo, force-push to main, curl|sh) before
they execute, especially when the command was generated by an LLM
role that might have been prompt-injected.

Higher score = riskier. Threshold for `safe`: < 30.

Categories + base weights (clamped at 100 total):
  push_to_main            90  (NEVER, per L7 §0.2)
  destructive_rm_root     90  (rm -rf /, /usr, /etc...)
  destructive_rm          60
  force_push              60
  privilege_escalation    50
  remote_exec             50  (curl|sh, wget|sh)
  loose_permissions       30  (chmod 777)
  destructive_reset       25  (git reset --hard — unless to autoevo/pre-*)
  rm_plain                15
  inplace_sed_awk         10
  system_path_mv          30
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import List


DEFAULT_SAFE_THRESHOLD = 30


@dataclass
class ActionFlag:
    category: str
    matched_text: str
    weight: int


@dataclass
class ActionScore:
    safe: bool
    score: int
    flags: List[ActionFlag] = field(default_factory=list)


# Patterns: (category, regex, weight)
_PATTERNS = [
    # Highest severity first
    ("push_to_main", re.compile(
        # git push origin main / git push origin master / git push --force-with-lease origin main
        r"\bgit\s+push\b[^&|;]*\b(?:origin\s+)?(?:main|master)\b",
    ), 90),
    ("destructive_rm_root", re.compile(
        # rm -rf / or rm -rf /etc, /usr, /bin, /sbin, /var, /Library, /System
        r"\brm\s+(?:-[a-zA-Z]*[rRf][a-zA-Z]*|--recursive|--force)+\s+/+(?:\s|$|etc|usr|bin|sbin|var|opt|library|system|home)",
        re.IGNORECASE,
    ), 90),
    ("destructive_rm", re.compile(
        r"\brm\s+-[a-zA-Z]*[rR][a-zA-Z]*[fF][a-zA-Z]*\s+\S"
        r"|\brm\s+-[a-zA-Z]*[fF][a-zA-Z]*[rR][a-zA-Z]*\s+\S",
    ), 60),
    ("force_push", re.compile(
        r"\bgit\s+push\b[^&|;]*--force(?:[^&|;]|$)"
        r"|\bgit\s+push\b[^&|;]*\s-f(?:\s|$)",
    ), 60),
    ("privilege_escalation", re.compile(
        r"^\s*sudo\b|\s&&\s*sudo\b|;\s*sudo\b",
    ), 50),
    ("remote_exec", re.compile(
        r"\b(curl|wget|fetch)\b[^|]*\|\s*(sh|bash|zsh)\b",
    ), 50),
    ("loose_permissions", re.compile(
        r"\bchmod\s+(?:0?7{2,}\d?|a\+w)",
    ), 30),
    ("system_path_mv", re.compile(
        r"\bmv\s+\S+\s+/(?:etc|usr|sbin|bin|var|System)/",
    ), 30),
    ("destructive_reset", re.compile(
        # git reset --hard <anything>; but allow autoevo/pre-* tags
        r"\bgit\s+reset\s+--hard\s+(?!autoevo/pre-)",
    ), 25),
    ("rm_plain", re.compile(
        r"\brm\s+(?!-[a-zA-Z]*[rRf])(?!/dev/null)\S",
    ), 15),
    ("inplace_sed_awk", re.compile(
        r"\b(sed|awk)\s+-i\b|\bperl\s+-i\b",
    ), 10),
]


def evaluate_action(cmd: str,
                     threshold: int = DEFAULT_SAFE_THRESHOLD) -> ActionScore:
    if not cmd or not isinstance(cmd, str):
        return ActionScore(safe=True, score=0)
    flags: List[ActionFlag] = []
    for category, pattern, weight in _PATTERNS:
        for m in pattern.finditer(cmd):
            flags.append(ActionFlag(category=category,
                                     matched_text=m.group(0),
                                     weight=weight))
    raw = sum(f.weight for f in flags)
    score = max(0, min(100, raw))
    return ActionScore(safe=(score < threshold), score=score, flags=flags)
