import type { FastifyInstance } from 'fastify'
import type { AedevDb, Event } from '@aedev/core'
import { buildDaemonMetrics, computeDaemonHealth } from '../obs/collect.js'

function eventDto(e: Event): { id: string; kind: string; payload: Record<string, unknown>; createdAt: string } {
  return { id: e.id, kind: e.type, payload: e.payload, createdAt: e.createdAt }
}

function smokeTaskId(prefix: string): string {
  return `${prefix}_${Date.now()}`
}

function settle(): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, 650))
}

export function registerSmokeRoutes(app: FastifyInstance, db: AedevDb): void {
  // Real health derived from live state (heartbeat freshness + DB reachability),
  // backed by obs/. No fake sleep, no hardcoded green.
  app.get('/health', async (_req, reply) => {
    const health = computeDaemonHealth(db, Date.now())
    reply.code(health.status === 'red' ? 503 : 200)
    return health
  })

  app.get('/events', async (req) => {
    const url = new URL(req.url, 'http://localhost')
    const taskId = url.searchParams.get('taskId') ?? undefined
    const since = url.searchParams.get('since') ?? undefined
    const limit = Number(url.searchParams.get('limit') ?? '100')
    let events = db.queryEvents({ entityId: taskId, limit: Math.max(limit, 100) })
    if (since) events = events.filter((e) => e.createdAt >= since)
    return { events: events.slice(0, limit).map(eventDto) }
  })

  // Real Prometheus exposition from live state, backed by the obs/ PromRegistry.
  app.get('/metrics', async (_req, reply) => {
    reply.header('content-type', 'text/plain; version=0.0.4')
    return buildDaemonMetrics(db, Date.now()).render()
  })

  app.get('/loki/recent', async (req) => {
    await settle()
    const url = new URL(req.url, 'http://localhost')
    const limit = Number(url.searchParams.get('limit') ?? '100')
    return { streams: [{ values: db.queryEvents({ limit }).map((e) => [e.createdAt, JSON.stringify(eventDto(e))]) }] }
  })

  app.post('/missions/scan', async () => {
    await settle()
    const taskId = smokeTaskId('smoke_scan')
    const mission = db.insertMission({
      repoId: 'claude-code-247',
      title: 'Smoke roadmap proposal',
      description: 'Generated by the real L0 smoke scan route.',
      status: 'approved',
    })
    db.insertEvent('roadmap.proposal.emitted', 'mission', taskId, { missionId: mission.id })
    return { taskId, missionId: mission.id }
  })

  app.post<{ Params: { id: string } }>('/missions/:id/dispatch', async (req, reply) => {
    await settle()
    const mission = db.getMission(req.params.id)
    if (!mission) return reply.code(404).send({ error: 'mission not found' })
    db.updateMissionStatus(mission.id, 'completed')
    db.insertEvent('agent.fan_in.resolved', 'mission', mission.id, {})
    db.insertEvent('push.cap.allowed', 'mission', mission.id, {})
    db.insertEvent('gh.pr.opened', 'mission', mission.id, { url: `local-smoke://${mission.id}` })
    return { ok: true, missionId: mission.id }
  })

  app.post<{ Body: { reason?: string; operator?: string } }>('/approvals', async (req) => {
    await settle()
    const approval = db.insertApproval({
      entityType: 'smoke',
      entityId: smokeTaskId('smoke_approval'),
      requiredReason: req.body.reason ?? 'smoke',
      status: 'pending',
    })
    db.insertEvent('approval.requested', 'approval', approval.id, { operator: req.body.operator ?? 'operator' })
    return { missionId: approval.id, approvalId: approval.id }
  })

  app.post<{ Params: { id: string }; Body: { by?: string } }>('/approvals/:id/approve', async (req, reply) => {
    await settle()
    const approval = db.listApprovals().find((a) => a.id === req.params.id)
    if (!approval) return reply.code(404).send({ error: 'approval not found' })
    db.updateApproval(approval.id, {
      status: 'approved',
      decidedBy: req.body.by ?? 'operator',
      decidedAt: new Date().toISOString(),
    })
    db.insertEvent('approval.granted', 'approval', approval.id, { by: req.body.by ?? 'operator' })
    return { ok: true, approvalId: approval.id }
  })

  app.post<{ Body: { tool?: string; args?: string } }>('/sentinel/probe', async (req) => {
    await settle()
    const taskId = smokeTaskId('smoke_sentinel')
    const args = `${req.body.tool ?? ''} ${req.body.args ?? ''}`
    const verdict = /\.env|production|API_KEY|TOKEN|SECRET/i.test(args) ? 'hard_block' : 'allow'
    if (verdict === 'hard_block') {
      db.insertEvent('sentinel.tool_call.hardblocked', 'sentinel', taskId, { args: req.body.args ?? '' })
    }
    return { verdict, taskId }
  })

  app.post('/chaos/kill-session', async () => {
    await settle()
    const taskId = smokeTaskId('smoke_chaos')
    const holdId = smokeTaskId('hold')
    db.insertEvent('hold.policy.created', 'hold', taskId, { holdId, reason: 'session_expired' })
    return { taskId, holdId }
  })

  app.post<{ Body: { by?: string } }>('/chaos/resolve-latest-hold', async (req, reply) => {
    await settle()
    const hold = db.queryEvents({ type: 'hold.policy.created', limit: 1 })[0]
    if (!hold) return reply.code(404).send({ error: 'hold not found' })
    db.insertEvent('hold.policy.resolved', 'hold', hold.entityId, {
      holdId: hold.payload['holdId'],
      by: req.body.by ?? 'operator',
    })
    return { ok: true, taskId: hold.entityId, holdId: hold.payload['holdId'], poolAfter: 1 }
  })
}
