#!/usr/bin/env python3
"""cluster_failures.py — L7 §6 Track M3.

Cluster FAILURES.md entries by keyword similarity so the operator can see
recurring failure patterns at a glance. Output: human-readable Markdown
report + machine-readable JSON.

Algorithm: iterative greedy clustering by Jaccard similarity on each
entry's keyword set. Threshold defaults to 0.20. No external ML deps.

Usage:
    scripts/cluster_failures.py
    scripts/cluster_failures.py --threshold 0.3 --out-md custom.md
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from dataclasses import dataclass, asdict, field
from pathlib import Path
from typing import List, Optional, Set


REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT / "scripts"))
import preflight_failures as pf  # noqa: E402


@dataclass
class Cluster:
    cluster_id: int
    members: List[str] = field(default_factory=list)
    shared_keywords: List[str] = field(default_factory=list)
    pattern_name: str = ""


def jaccard(a: Set[str], b: Set[str]) -> float:
    if not a and not b:
        return 0.0
    inter = a & b
    union = a | b
    if not union:
        return 0.0
    return len(inter) / len(union)


def cluster_entries(entries: List[pf.FailureEntry],
                     threshold: float = 0.20) -> List[Cluster]:
    """Greedy single-linkage clustering by keyword Jaccard.

    Each entry is placed into the first existing cluster where its
    keyword set has Jaccard >= threshold with at least one member's
    keyword set. Else it starts a new cluster.
    """
    if not entries:
        return []
    kw_by_id = {e.id: set(e.keywords) for e in entries}

    clusters: List[Cluster] = []
    for entry in entries:
        ekw = kw_by_id[entry.id]
        placed = False
        for c in clusters:
            for mid in c.members:
                if jaccard(ekw, kw_by_id[mid]) >= threshold:
                    c.members.append(entry.id)
                    placed = True
                    break
            if placed:
                break
        if not placed:
            clusters.append(Cluster(cluster_id=len(clusters) + 1,
                                     members=[entry.id]))

    # Compute shared keywords + pattern name per cluster
    for c in clusters:
        member_kw_sets = [kw_by_id[m] for m in c.members]
        if not member_kw_sets:
            continue
        if len(member_kw_sets) == 1:
            c.shared_keywords = sorted(member_kw_sets[0])[:5]
            c.pattern_name = c.shared_keywords[0] if c.shared_keywords else ""
            continue
        shared = set.intersection(*member_kw_sets) if member_kw_sets else set()
        if shared:
            c.shared_keywords = sorted(shared)[:8]
        else:
            # Union with frequency: take the most common keywords across
            # the cluster as the "shared theme".
            counter = Counter()
            for s in member_kw_sets:
                counter.update(s)
            c.shared_keywords = [k for k, _ in counter.most_common(8)]
        c.pattern_name = c.shared_keywords[0] if c.shared_keywords else ""
    return clusters


def render_md(clusters: List[Cluster], n_entries: int,
              threshold: float) -> str:
    lines = [
        "# FAILURES clusters (generated)",
        "",
        f"> Generated by `scripts/cluster_failures.py`. "
        f"Total entries: {n_entries}. Clusters: {len(clusters)}. "
        f"Jaccard threshold: {threshold}.",
        "",
    ]
    for c in clusters:
        lines.append(f"## Cluster {c.cluster_id}: {c.pattern_name or '(unnamed)'}")
        lines.append("")
        lines.append(f"- Members ({len(c.members)}): "
                     f"{', '.join(c.members)}")
        if c.shared_keywords:
            lines.append(f"- Theme keywords: {', '.join(c.shared_keywords)}")
        lines.append("")
    return "\n".join(lines)


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        description="Cluster FAILURES.md entries by keyword similarity"
    )
    parser.add_argument("--failures", default=str(REPO_ROOT / "FAILURES.md"))
    parser.add_argument("--threshold", type=float, default=0.20)
    parser.add_argument("--out-md",
                        default=str(REPO_ROOT / "reports"
                                    / "failure-clusters.md"))
    parser.add_argument("--out-json",
                        default=str(REPO_ROOT / "reports"
                                    / "failure-clusters.json"))
    args = parser.parse_args(argv)

    entries = pf.parse_failures(Path(args.failures))
    clusters = cluster_entries(entries, threshold=args.threshold)

    Path(args.out_md).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out_md).write_text(
        render_md(clusters, len(entries), args.threshold)
    )
    payload = {
        "n_entries": len(entries),
        "threshold": args.threshold,
        "clusters": [asdict(c) for c in clusters],
    }
    Path(args.out_json).write_text(json.dumps(payload, indent=2))
    print(f"[cluster_failures] {len(entries)} entries → {len(clusters)} clusters")
    print(f"[cluster_failures] wrote {args.out_md} + {args.out_json}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
